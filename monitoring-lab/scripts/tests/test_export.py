import pytest

from export_checkmk import (
    Host,
    UnsupportedRule,
    build,
    effective_params,
    folder_contains,
    map_service,
    plugin_of,
    split_by_group,
    write_outputs,
)


def rule(folder, value, description="", index=0, host_names=None, disabled=False, tags=None):
    conditions = {"host_tags": tags or [], "host_label_groups": [], "service_label_groups": []}
    if host_names:
        conditions["host_name"] = {"match_on": host_names, "operator": "one_of"}
    return {
        "id": description or folder,
        "folder": folder,
        "folder_index": index,
        "value_raw": value,
        "properties": {"description": description, "disabled": disabled},
        "conditions": conditions,
    }


APP01 = Host("app01", "/linux/app")
DB01 = Host("db01", "/linux/db")
DEFAULTS = {"levels": (80.0, 90.0)}


def test_folder_matching():
    assert folder_contains("/", "/linux/app")
    assert folder_contains("/linux", "/linux/app")
    assert folder_contains("/linux/app", "/linux/app")
    assert not folder_contains("/linux/app", "/linux/application")
    assert not folder_contains("/linux/db", "/linux/app")


def test_subfolder_rule_wins_over_parent():
    rules = [rule("/linux", "{'levels': (80.0, 90.0)}", "default"), rule("/linux/db", "{'levels': (90.0, 95.0)}", "db")]
    params, sources = effective_params(rules, DB01, DEFAULTS)
    assert params["levels"] == (90.0, 95.0)
    assert sources == ["db (/linux/db)"]


def test_host_rule_only_applies_to_that_host():
    rules = [rule("/linux", "{'levels15': (2.0, 4.0)}", "app02 only", host_names=["app02"])]
    params, sources = effective_params(rules, APP01, {"levels15": (5.0, 10.0)})
    assert params["levels15"] == (5.0, 10.0)
    assert sources == ["Checkmk default for levels15"]


def test_dictionary_rules_merge_key_by_key():
    rules = [
        rule("/linux/app", "{'levels': (70.0, 85.0)}", "app levels"),
        rule("/linux", "{'levels': (80.0, 90.0), 'trend_range': 24}", "default"),
    ]
    params, _ = effective_params(rules, APP01, DEFAULTS)
    assert params == {"levels": (70.0, 85.0), "trend_range": 24}


def test_disabled_rules_are_ignored():
    rules = [rule("/linux", "{'levels': (50.0, 60.0)}", "off", disabled=True)]
    params, _ = effective_params(rules, APP01, DEFAULTS)
    assert params["levels"] == (80.0, 90.0)


def test_tag_conditions_are_not_guessed():
    with pytest.raises(UnsupportedRule):
        effective_params([rule("/", "{'levels': (1.0, 2.0)}", tags=[{"key": "criticality"}])], APP01, DEFAULTS)


def test_filesystem_used_levels_become_check_disk_free_levels():
    check = map_service("df", "Filesystem /boot/efi", {"levels": (80.0, 90.0)})
    assert check["nrpe"] == "check_disk_boot_efi"
    assert check["command"].endswith("check_disk -w 20% -c 10% -p /boot/efi")


def test_plugin_names_drop_arguments():
    assert plugin_of("check_mk-df") == "df"
    assert plugin_of("check-mk-ping!-w 200.00,80.00% -c 500.00,100.00% app01") == "check-mk-ping"


def test_unknown_plugins_go_to_triage():
    assert map_service("lnx_thermal", "Temperature Zone 0", {}) is None


def test_checks_shared_by_a_folder_go_to_group_vars():
    hosts = [Host("app01", "/linux/app"), Host("app02", "/linux/app")]
    disk = {"name": "Filesystem /", "nrpe": "check_disk_root", "command": "x"}
    by_host = {
        "app01": [disk, {"name": "CPU load", "command": "a"}],
        "app02": [disk, {"name": "CPU load", "command": "b"}],
    }
    groups, host_checks = split_by_group(hosts, by_host)
    assert groups == {"folder_app": [disk]}
    assert [c["command"] for c in host_checks["app02"]] == ["b"]


def test_build_end_to_end():
    hosts = [APP01, DB01]
    services = [
        {"host_name": "app01", "description": "Filesystem /", "check_command": "check_mk-df"},
        {"host_name": "db01", "description": "Filesystem /", "check_command": "check_mk-df"},
        {"host_name": "db01", "description": "Backup_age", "check_command": "check_mk-mrpe"},
        {"host_name": "db01", "description": "Uptime", "check_command": "check_mk-uptime"},
    ]
    rules = {"checkgroup_parameters:filesystem": [rule("/linux/db", "{'levels': (90.0, 95.0)}", "db")]}
    result = build(hosts, services, rules)
    assert "-w 20% -c 10%" in result["group_checks"]["folder_app"][0]["command"]
    db_checks = {c["name"]: c for c in result["group_checks"]["folder_db"]}
    assert "-w 10% -c 5%" in db_checks["Filesystem /"]["command"]
    assert db_checks["Backup_age"]["shared_plugin"] == "Backup_age"
    assert result["triage"]["uptime"]["services"] == ["db01: Uptime"]


def test_write_outputs_replaces_the_previous_export(tmp_path):
    stale = tmp_path / "host_vars/gone01/nagios.yml"
    stale.parent.mkdir(parents=True)
    stale.write_text("# Generated by scripts/export_checkmk.py from Checkmk site 'lab'\nnagios_host_checks: []\n")
    kept = tmp_path / "host_vars/app01/notes.yml"
    kept.parent.mkdir(parents=True)
    kept.write_text("hand_written: true\n")
    result = {"group_checks": {"folder_app": []}, "host_checks": {}, "triage": {}, "report": []}
    write_outputs(result, tmp_path, "lab")
    assert not stale.exists() and not stale.parent.exists()
    assert kept.exists()
    assert (tmp_path / "group_vars/folder_app/nagios.yml").exists()
